#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum AmmoType {
    None = 0,
    Bullets = 1,
    Shells = 2,
    Bolts = 3,
    Explosives = 4,
    Energy = 5,
}

impl AmmoType {
    pub const fn from_u8(v: u8) -> Self {
        match v {
            0 => Self::None,
            1 => Self::Bullets,
            2 => Self::Shells,
            3 => Self::Bolts,
            4 => Self::Explosives,
            5 => Self::Energy,
            _ => Self::None,
        }
    }
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::None => "None",
            Self::Bullets => "Bullets",
            Self::Shells => "Shells",
            Self::Bolts => "Bolts",
            Self::Explosives => "Explosives",
            Self::Energy => "Energy",
        }
    }
}

