pub const fn ammo_max(kind: AmmoType) -> u16 {
    match kind {
        AmmoType::None => 1000,
        AmmoType::Bullets => 255,
        AmmoType::Shells => 55,
        AmmoType::Bolts => 55,
        AmmoType::Explosives => 55,
        AmmoType::Energy => 55,
    }
}

pub const fn ammo_pickup(kind: AmmoType) -> u16 {
    match kind {
        AmmoType::None => 0,
        AmmoType::Bullets => 32,
        AmmoType::Shells => 8,
        AmmoType::Bolts => 7,
        AmmoType::Explosives => 6,
        AmmoType::Energy => 10,
    }
}
