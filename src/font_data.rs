//! OG bitmap fonts from the recreation's GameMaker font resources
//! (`fonts/fntM1`, `fonts/fntBig`). `draw_text_nt` renders the HUD and
//! menus through `draw_set_font(fntM1)` and `draw_text_bigname` uses
//! `fntBig` at `0.65`; the glyph tables below are the `.yy` metrics
//! verbatim (`x/y/w/h` in the page, `shift` = the advance, `offset` =
//! the left bearing), generated from the recreation.

pub struct Glyph {
    pub ch: char,
    pub x: u16,
    pub y: u16,
    pub w: u16,
    pub h: u16,
    pub shift: u8,
    pub offset: i8,
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Font {
    Main,
    Big,
}

impl Font {
    pub fn path(self) -> &'static str {
        match self {
            Font::Main => "images/fntM1.png",
            Font::Big => "images/fntBig.png",
        }
    }
    fn glyphs(self) -> &'static [Glyph] {
        match self {
            Font::Main => MAIN_GLYPHS,
            Font::Big => BIG_GLYPHS,
        }
    }
}

pub fn glyph(font: Font, ch: char) -> Option<&'static Glyph> {
    let table = font.glyphs();
    table
        .binary_search_by(|g| g.ch.cmp(&ch))
        .ok()
        .map(|i| &table[i])
}

impl Font {
    /// The font's tallest ink height, which is what `font_get_string_height`
    /// reports for a line of text.
    pub fn line_height(self) -> u32 {
        self.glyphs()
            .iter()
            .map(|g| u32::from(g.h))
            .max()
            .unwrap_or(8)
    }
}

/// GML `font_get_string_width`: the sum of the advances.
pub fn text_width(font: Font, text: &str) -> u32 {
    text.chars()
        .filter(|c| *c != '\n')
        .map(|c| glyph(font, c).map_or(4, |g| u32::from(g.shift)))
        .sum()
}

